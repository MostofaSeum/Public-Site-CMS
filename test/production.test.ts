import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { checkProductionApi, checkProductionFiles, siteOf, summarize } from '../src/cli/doctor';
import { runInit, type InitOptions } from '../src/cli/init';
import { providersV1 } from '../src/cli/templates';
import { memoryAdapter } from '../src/adapters/memory';
import { getAllPageContent } from '../src/next/getPageContent';

const LAYOUT = `import "./globals.css";

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en">
      <body>{children}</body>
    </html>
  );
}
`;

function makeProject(dir: string, opts: { next?: string; nextConfig?: string } = {}) {
  fs.mkdirSync(path.join(dir, 'app'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify({ dependencies: { next: opts.next ?? '15.5.0', tailwindcss: '^4' } }));
  fs.writeFileSync(path.join(dir, 'tsconfig.json'), '{ "compilerOptions": { "resolveJsonModule": true, "paths": { "@/*": ["./*"] } } }');
  fs.writeFileSync(path.join(dir, 'app', 'layout.tsx'), LAYOUT);
  fs.writeFileSync(path.join(dir, 'app', 'globals.css'), '@import "tailwindcss";\n');
  if (opts.nextConfig) fs.writeFileSync(path.join(dir, 'next.config.ts'), opts.nextConfig);
}

describe('server rendering of CMS content', () => {
  let dir: string;
  const options = (over: Partial<InitOptions> = {}): InitOptions => ({
    cwd: dir, backend: 'django', apiUrl: 'http://localhost:8000/api/cms', adminPath: 'admin/cms',
    example: true, install: false, dryRun: false, force: false, ...over,
  });
  const read = (...p: string[]) => fs.readFileSync(path.join(dir, ...p), 'utf8');
  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'storio-editor-prod-'));
  });
  afterEach(() => {
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it('loads content on every request for Next 15+ (connection), with a client provider beside it', () => {
    makeProject(dir);
    runInit(options());
    const server = read('components', 'CmsProviders.tsx');
    expect(server).not.toContain("'use client'");
    expect(server).toContain("import { connection } from 'next/server';");
    expect(server).toContain('await connection();');
    expect(server).toContain('getAllPageContent(cms, { storage })');
    expect(read('components', 'CmsClientProviders.tsx')).toContain('<CmsProvider config={cms} initialContent={initialContent}>');
    expect(read('app', 'layout.tsx')).toContain('<CmsProviders>{children}</CmsProviders>');
  });

  it('uses "use cache" with cacheComponents and never generates `export const dynamic`', () => {
    makeProject(dir, { next: '16.4.6', nextConfig: 'const nextConfig = {\n  cacheComponents: true,\n};\nexport default nextConfig;\n' });
    runInit(options());
    const server = read('components', 'CmsProviders.tsx');
    expect(server).toContain("'use cache';");
    expect(server).toContain("cacheLife('minutes');");
    expect(server).not.toContain('connection');
    const example = read('app', 'cms-example', 'page.tsx');
    expect(example).not.toContain('dynamic');
    expect(example).toContain('return <CmsExampleView />;');
  });

  it('uses noStore on Next 14', () => {
    makeProject(dir, { next: '14.2.0' });
    runInit(options());
    expect(read('components', 'CmsProviders.tsx')).toContain('noStore();');
  });

  it('upgrades a provider generated by an older version, but never a customised one', () => {
    makeProject(dir);
    fs.mkdirSync(path.join(dir, 'components'));
    fs.writeFileSync(path.join(dir, 'components', 'CmsProviders.tsx'), providersV1('@/cms.config'));
    const report = runInit(options());
    expect(report.actions.find((a) => a.file === 'components/CmsProviders.tsx')).toMatchObject({ kind: 'overwritten' });
    expect(read('components', 'CmsProviders.tsx')).toContain('getAllPageContent');

    const custom = providersV1('@/cms.config').replace('return', '// mine\n  return');
    fs.writeFileSync(path.join(dir, 'components', 'CmsProviders.tsx'), custom);
    runInit(options());
    expect(read('components', 'CmsProviders.tsx')).toBe(custom);
  });

  it('reads the API URL from NEXT_PUBLIC_CMS_API_URL with the dev URL as fallback', () => {
    makeProject(dir);
    runInit(options());
    expect(read('cms.config.ts')).toContain("const API_URL = process.env.NEXT_PUBLIC_CMS_API_URL ?? 'http://localhost:8000/api/cms';");
  });

  it('getAllPageContent merges published records for every page and falls back to defaults', async () => {
    const config = {
      pages: [
        { key: 'home', title: 'Home', route: '/', sections: [{ key: 'hero', label: 'Hero' }], defaults: { hero: { title: 'Default' } } },
        { key: 'about', title: 'About', route: '/about', sections: [{ key: 'hero', label: 'Hero' }], defaults: { hero: { title: 'About us' } } },
      ],
    };
    const storage = memoryAdapter();
    await storage.saveRecord({ page: 'home', sectionKey: 'hero', content: { title: 'Edited' }, isPublished: true });
    await storage.saveRecord({ page: 'about', sectionKey: 'hero', content: { title: 'Draft only' }, isPublished: false });
    const all = await getAllPageContent(config, { storage });
    expect(all).toEqual({ home: { hero: { title: 'Edited' } }, about: { hero: { title: 'About us' } } });

    const broken = { ...storage, listRecords: async () => { throw new Error('down'); } };
    expect(await getAllPageContent(config, { storage: broken })).toEqual({ home: { hero: { title: 'Default' } }, about: { hero: { title: 'About us' } } });
  });
});

describe('doctor --production', () => {
  let dir: string;
  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'storio-editor-prodfiles-'));
  });
  afterEach(() => {
    fs.rmSync(dir, { recursive: true, force: true });
  });
  const titles = (checks: { level: string; title: string }[], level: string) => checks.filter((c) => c.level === level).map((c) => c.title).join(' | ');

  it('flags a hardcoded localhost API, a dev-only authorize and client-only content', () => {
    makeProject(dir);
    fs.writeFileSync(path.join(dir, 'cms.config.ts'), "djangoAdapter({ baseUrl: 'http://localhost:8000/api/cms' })");
    fs.mkdirSync(path.join(dir, 'components'));
    fs.writeFileSync(path.join(dir, 'components', 'CmsProviders.tsx'), providersV1('@/cms.config'));
    const checks = checkProductionFiles(dir);
    expect(titles(checks, 'fail')).toMatch(/hardcoded to http:\/\/localhost/);
    expect(titles(checks, 'warn')).toMatch(/only loaded in the browser/);
  });

  it('passes a fresh Django setup and warns about file storage and dev-only saving', () => {
    makeProject(dir);
    runInit({ cwd: dir, backend: 'django', apiUrl: 'http://localhost:8000/api/cms', adminPath: 'admin/cms', example: false, install: false, dryRun: false, force: false });
    expect(titles(checkProductionFiles(dir), 'fail')).toBe('');

    const files = fs.mkdtempSync(path.join(os.tmpdir(), 'storio-editor-prodfiles2-'));
    makeProject(files);
    runInit({ cwd: files, backend: 'files', apiUrl: '', adminPath: 'admin/cms', example: false, install: false, dryRun: false, force: false });
    const checks = checkProductionFiles(files);
    expect(titles(checks, 'warn')).toMatch(/JSON file/);
    expect(titles(checks, 'fail')).toMatch(/next dev/);
    fs.rmSync(files, { recursive: true, force: true });
  });

  const reply = (status: number, headers: Record<string, string> = {}, body = '') => ({
    status,
    headers: { get: (n: string) => headers[n.toLowerCase()] ?? null },
    text: async () => body,
  });

  it('passes a correct production API on a subdomain', async () => {
    const checks = await checkProductionApi('https://api.example.com/api/cms', 'https://example.com', async (url) =>
      url.endsWith('/csrf')
        ? reply(200, {
            'access-control-allow-origin': 'https://example.com',
            'access-control-allow-credentials': 'true',
            'set-cookie': 'csrftoken=abc; expires=Tue, 16 Nov 2027 08:48:58 GMT; Max-Age=31449600; Path=/; SameSite=Lax; Secure',
          })
        : reply(404, {}, '<h1>Not Found</h1>')
    );
    expect(summarize(checks).fail).toBe(0);
    expect(titles(checks, 'ok')).toMatch(/same site \(example.com\)/);
  });

  it('catches HTTP, insecure cookies, DEBUG, missing CORS and different sites', async () => {
    const checks = await checkProductionApi('http://myapi.herokuapp.com/api/cms', 'https://mysite.vercel.app', async (url) =>
      url.endsWith('/csrf') ? reply(200, { 'set-cookie': 'csrftoken=abc; Path=/; SameSite=Lax' }) : reply(404, {}, "You're seeing this error because you have DEBUG = True")
    );
    const failures = titles(checks, 'fail');
    expect(failures).toMatch(/API does not use HTTPS/);
    expect(failures).toMatch(/different sites/);
    expect(failures).toMatch(/CORS/);
    expect(failures).toMatch(/not marked Secure/);
    expect(failures).toMatch(/SameSite=Lax across different sites/);
    expect(failures).toMatch(/DEBUG = True/);
  });

  it('explains an unreachable API and a missing route', async () => {
    const down = await checkProductionApi('https://api.example.com/api/cms', 'https://example.com', async () => {
      throw new Error('ENOTFOUND');
    });
    expect(titles(down, 'fail')).toMatch(/Cannot reach/);
    const missing = await checkProductionApi('https://api.example.com/api/cms', 'https://example.com', async () => reply(404));
    expect(missing.find((c) => c.level === 'fail')?.fix).toMatch(/storio_elements_editor\.urls/);
  });

  it('tells sites apart', () => {
    expect(siteOf('https://api.example.com/x')).toBe('example.com');
    expect(siteOf('https://example.com')).toBe('example.com');
    expect(siteOf('https://a.vercel.app')).not.toBe(siteOf('https://b.herokuapp.com'));
  });
});
